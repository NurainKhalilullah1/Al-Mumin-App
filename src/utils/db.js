export const getClasses = async () => {
  let classes = [];
  try {
    // Try fetching with student count
    const { data, error } = await supabase.from('classes').select('*, students(count)').order('name');
    if (error) throw error;
    classes = data;
  } catch (err) {
    // console.warn("Relation fetch failed, retrying simple select...");
    // Fallback: Fetch without relation
    const { data, error } = await supabase.from('classes').select('*').order('name');
    if (!error) classes = data || [];
  }

  // Fetch verified Form Teachers from Staff Table
  // If 'assigned_class' column is missing, this might also fail silently or return error. 
  // We can wrap this too to be safe.
  let staff = [];
  try {
    const { data } = await supabase.from('staff').select('name, assigned_class').not('assigned_class', 'is', null);
    staff = data || [];
  } catch (e) { /* Ignore if column missing */ }

  // Create Map: { 'JSS 1': 'Mr. Ibrahim', 'JSS 2': 'Mrs. Amina' }
  const teacherMap = {};
  if (staff) {
    staff.forEach(s => {
      if (s.assigned_class) teacherMap[s.assigned_class] = s.name;
    });
  }

  return classes.map(c => ({
    ...c,
    formTeacher: teacherMap[c.name] || c.form_teacher || null, // Prioritize active staff assignment
    studentCount: c.students ? c.students[0]?.count : 0
  }));
};

