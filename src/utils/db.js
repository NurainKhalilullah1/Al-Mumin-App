export const saveScore = async (studentId, term, subject, test1, test2, midTerm, exam, approvalStatus = 'Pending') => {
  const t1 = parseInt(test1) || 0;
  const t2 = parseInt(test2) || 0;
  const mt = parseInt(midTerm) || 0;
  const ex = parseInt(exam) || 0;

  // Calculate grade logic locally or database generated logic if simpler
  // Supposing we keep logic here:
  const total = t1 + t2 + mt + ex;
  let grade = 'F';
  let remark = 'Fail';
  if (total >= 70) { grade = 'A'; remark = 'Excellent'; }
  else if (total >= 60) { grade = 'B'; remark = 'Very Good'; }
  else if (total >= 50) { grade = 'C'; remark = 'Credit'; }
  else if (total >= 40) { grade = 'D'; remark = 'Pass'; }

  const payload = {
    student_id: studentId,
    term,
    subject,
    test1: t1,
    test2: t2,
    mid_term: mt,
    exam: ex,
    total: total,
    grade,
    remark,
    approval_status: approvalStatus
  };

  // Check existing result
  const { data: existing, error: checkError } = await supabase.from('results')
    .select('id')
    .eq('student_id', String(studentId))
    .eq('term', term)
    .eq('subject', subject)
    .maybeSingle();

  if (checkError) {
    console.error("Error checking existing score:", JSON.stringify(checkError));
    return;
  }

  if (existing) {
    const { error: updateError } = await supabase.from('results').update(payload).eq('id', existing.id);
    if (updateError) console.error("Error updating score:", JSON.stringify(updateError));
  } else {
    const { error: insertError } = await supabase.from('results').insert([payload]);
    if (insertError) console.error("Error inserting score:", JSON.stringify(insertError));
  }
};

