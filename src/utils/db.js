// --- APPLICANT MANAGEMENT ---
export const saveApplicant = async (appData) => {
  // Basic validation
  if (!appData.name || !appData.classLevel) return null;

  const payload = {
    name: appData.name,
    age: parseInt(appData.age),
    class_level: appData.classLevel,
    parent_name: appData.parentName,
    parent_phone: appData.parentPhone,
    status: 'Pending'
  };

  if (appData.createdBy) {
    payload.created_by = appData.createdBy;
  }

  try {
    if (appData.id) {
      const { error } = await supabase.from('applicants').update(payload).eq('id', appData.id);
      if (error) throw error;
    } else {
      const newId = `APP-${Date.now()}`;
      const { error } = await supabase.from('applicants').insert([{ id: newId, ...payload }]);
      if (error) throw error;
    }
  } catch (error) {
    // Graceful Fallback for missing 'created_by' column
    if ((error.code === 'PGRST204' || error.message.includes('created_by')) && payload.created_by) {
      //   console.warn("created_by column missing. Retrying without it.");
      delete payload.created_by;
      if (appData.id) {
        await supabase.from('applicants').update(payload).eq('id', appData.id);
      } else {
        const newId = `APP-${Date.now()}`;
        await supabase.from('applicants').insert([{ id: newId, ...payload }]);
      }
    } else {
      console.error("Error saving applicant:", error);
    }
  }
};

